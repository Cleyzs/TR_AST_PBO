    private java.awt.CardLayout cardLayout;

    public void tampilkanKartu(String nama) {
        cardLayout.show(kartu, nama);
        setAktif(nama);
    }

    private void setAktif(String nama) {
        javax.swing.JButton[] tombol = {
            menuDashboard, menuLayanan, menuPelanggan, menuPegawai,
            menuPesanan, menuDaftarPesanan, menuRiwayat, menuLaporan
        };
        String[] kunci = {
            "beranda", "formLayanan", "formPelanggan", "formPegawai",
            "formPesanan", "daftarPesanan", "riwayatPelanggan", "laporanPendapatan"
        };
        for (int i = 0; i < tombol.length; i++) {
            boolean aktif = kunci[i].equals(nama);
            tombol[i].setOpaque(aktif);
            tombol[i].setContentAreaFilled(aktif);
            tombol[i].setBackground(aktif
                    ? java.awt.Color.decode("#A0D8EF") : new java.awt.Color(0,0,0,0));
            tombol[i].setForeground(aktif
                    ? java.awt.Color.decode("#1F4650") : java.awt.Color.decode("#FFFFF2"));
            tombol[i].setFont(new java.awt.Font("Segoe UI",
                    aktif ? java.awt.Font.BOLD : java.awt.Font.PLAIN, 14));
            tombol[i].repaint();
        }
    }
    
