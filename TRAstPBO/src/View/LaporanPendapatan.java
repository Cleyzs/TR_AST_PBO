    /** Tanggal awal untuk dikirim ke Controller. */
    public java.sql.Date getTanggalAwal() {
        return new java.sql.Date(((java.util.Date) spinnerDari.getValue()).getTime());
    }

    /** Tanggal akhir untuk dikirim ke Controller. */
    public java.sql.Date getTanggalAkhir() {
        return new java.sql.Date(((java.util.Date) spinnerSampai.getValue()).getTime());
    }

    /** Controller memanggil ini untuk menampilkan total pendapatan. */
    public void setTotalPendapatan(double total) {
        nilaiTotal.setText("Rp " + java.text.NumberFormat.getNumberInstance(
                new java.util.Locale("id", "ID")).format(total));
    }

    /** Controller memanggil ini untuk mengisi tabel dengan data yang sudah jadi. */
    public void setDataTabel(Object[][] data) {
        javax.swing.table.DefaultTableModel m =
                (javax.swing.table.DefaultTableModel) tabel.getModel();
        m.setRowCount(0);
        if (data != null) {
            for (Object[] baris : data) {
                m.addRow(baris);
            }
        }
    }

